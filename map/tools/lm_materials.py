_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_CACHE = {}


def _find(fname):
    for d in ("H_dark", "H", "G", "C", "A", "F"):
        p = os.path.join(_ROOT, "ref", d, fname)
        if os.path.exists(p):
            return p
    return None


def mat(key):
    """Return (and cache) the Blender material for a landmark material key."""
    if key in _CACHE:
        return _CACHE[key]
    if key not in SPECS:
        raise KeyError("unknown lm material %r (have %s)" % (key, sorted(SPECS)))
    fname, tint, rough, metallic = SPECS[key]
    name = "LMM_" + key
    existing = None
    try:
        import bpy
        existing = bpy.data.materials.get(name)
    except Exception:
        existing = None
    if existing is not None:
        _CACHE[key] = existing
        return existing
    if _find(fname):
        m = kit.mat_texture(name, fname, rough=rough, metallic=metallic, tint=tint)
    else:
        m = kit.mat_solid(name, tint, rough=rough, metallic=metallic)
    _CACHE[key] = m
    return m


def keys():
    return sorted(SPECS.keys())
